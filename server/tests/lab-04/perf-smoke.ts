import request from "supertest";
import { getPrisma } from "../../src/prisma.js";
import { app } from "../../src/app.js";
import { SEED_PASSWORDS, seedGraded } from "../../src/seed/graded-seed.js";

// Performance smoke - tests.md 2.7, PERF-01 and PERF-02 (C-148, C-183, AC-102,
// BR-72). Run with `npm run test:perf`. It is not part of `npm test`, so the
// Supertest counts stay stable.
//
// It refuses to start unless DATABASE_URL names toktickit_perf. It fills that
// database itself, idempotently, to about 2,000 Tickets and 5,000 actions
// (rows are marked by the PERF- Ticket number, and a second run adds nothing
// once the targets are met), then makes ten warm-up requests and 50 timed
// requests per dashboard endpoint and takes the p95 by nearest rank. The
// EXPLAIN (ANALYZE, BUFFERS) of each dashboard query is printed as information
// and is never asserted (C-148): at 2,000 rows Postgres may rightly prefer a
// sequential scan. Exit code 1 if a p95 is not under 500 ms.

const DATABASE = "toktickit_perf";
const TARGET_TICKETS = 2000;
const TARGET_ACTIONS = 5000;
const WARM_UP = 10;
const TIMED = 50;
const LIMIT_MS = 500;

const STATUSES = ["NEW", "OPEN", "IN_PROGRESS", "WAITING_FOR_REQUESTER", "RESOLVED", "CLOSED", "REOPENED", "CANCELLED"] as const;
const PRIORITIES = ["LOW", "MEDIUM", "HIGH"] as const;
const DAY = 24 * 60 * 60 * 1000;

function databaseName(): string | null {
  const url = process.env.DATABASE_URL;
  if (!url) return null;
  try {
    return new URL(url).pathname.replace(/^\//, "");
  } catch {
    return null;
  }
}

async function fill() {
  const prisma = getPrisma();
  await seedGraded(prisma);
  const users = await prisma.user.findMany({ where: { isActive: true }, orderBy: { id: "asc" } });
  const requesters = users.filter((u) => u.role === "REQUESTER");
  const staff = users.filter((u) => u.role !== "REQUESTER");
  const mostTickets = requesters.find((u) => u.email === "anucha.p@example.ac.th") ?? requesters[0];
  const category = await prisma.category.findFirstOrThrow();
  const system = await prisma.relatedSystem.findFirstOrThrow();

  const perfTickets = await prisma.ticket.count({ where: { ticketNumber: { startsWith: "PERF-" } } });
  const now = Date.now();
  if (perfTickets < TARGET_TICKETS) {
    const rows = [];
    for (let i = perfTickets; i < TARGET_TICKETS; i++) {
      const status = STATUSES[i % STATUSES.length];
      const owned = status !== "NEW";
      const created = new Date(now - (1 + (i % 60)) * DAY);
      const active = new Date(now - (i % 25) * DAY - (i % 24) * 60 * 60 * 1000);
      rows.push({
        ticketNumber: `PERF-${String(i + 1).padStart(6, "0")}`,
        // Three quarters belong to the Requester with the most Tickets (PERF-01).
        requesterId: i % 4 === 3 ? requesters[i % requesters.length].id : mostTickets.id,
        categoryId: category.id,
        relatedSystemId: system.id,
        ownerId: owned ? staff[i % staff.length].id : null,
        summary: `Perf fixture ticket ${i + 1}`,
        description: "Generated by perf-smoke.ts (C-183).",
        requestedPriority: PRIORITIES[i % 3],
        itPriority: PRIORITIES[(i * 7) % 3],
        currentStatus: status,
        requesterResolvedAt: status === "RESOLVED" && i % 5 === 0 ? active : null,
        createdAt: created,
        lastActivityAt: active < created ? created : active,
        resolvedAt: status === "RESOLVED" || status === "CLOSED" ? active : null,
      });
    }
    for (let at = 0; at < rows.length; at += 500) await prisma.ticket.createMany({ data: rows.slice(at, at + 500) });
  }

  const perfActions = await prisma.actionTaken.count({ where: { ticket: { ticketNumber: { startsWith: "PERF-" } } } });
  if (perfActions < TARGET_ACTIONS) {
    const tickets = await prisma.ticket.findMany({ where: { ticketNumber: { startsWith: "PERF-" } }, orderBy: { id: "asc" }, select: { id: true, createdAt: true } });
    const rows = [];
    for (let i = perfActions; i < TARGET_ACTIONS; i++) {
      const ticket = tickets[i % tickets.length];
      const planned = i % 5 === 0;
      const person = staff[i % staff.length];
      const at = new Date(ticket.createdAt.getTime() + (1 + (i % 48)) * 60 * 60 * 1000);
      rows.push({
        ticketId: ticket.id,
        status: planned ? ("PLANNED" as const) : ("COMPLETED" as const),
        actionAt: at,
        description: `Perf fixture action ${i + 1}`,
        result: planned ? null : "Done.",
        followUpRequired: false,
        assigneeId: person.id,
        performedById: planned ? null : person.id,
        finishedAt: planned ? null : at,
        createdById: person.id,
        createdAt: at,
      });
    }
    for (let at = 0; at < rows.length; at += 500) await prisma.actionTaken.createMany({ data: rows.slice(at, at + 500) });
  }
  const tickets = await prisma.ticket.count();
  const actions = await prisma.actionTaken.count();
  console.log(`Fixture: ${tickets} Tickets (${await prisma.ticket.count({ where: { ticketNumber: { startsWith: "PERF-" } } })} perf), ${actions} actions.`);
  return { mostTickets, tickets, actions };
}

async function signIn(email: string, password: string) {
  const res = await request(app).post("/api/auth/login").send({ email, password });
  if (res.status !== 200) throw new Error(`sign-in as ${email} failed with ${res.status}`);
  const cookie = (res.headers["set-cookie"] as unknown as string[]).map((c) => c.split(";")[0]).join("; ");
  return cookie;
}

async function measure(path: string, cookie: string): Promise<number[]> {
  for (let i = 0; i < WARM_UP; i++) {
    const res = await request(app).get(path).set("Cookie", cookie);
    if (res.status !== 200) throw new Error(`${path} answered ${res.status}`);
  }
  const times: number[] = [];
  for (let i = 0; i < TIMED; i++) {
    const t0 = performance.now();
    const res = await request(app).get(path).set("Cookie", cookie);
    times.push(performance.now() - t0);
    if (res.status !== 200) throw new Error(`${path} answered ${res.status}`);
  }
  return times;
}

// Nearest rank: the smallest value with at least 95 % of the samples at or below it.
function p95(times: number[]): number {
  const sorted = [...times].sort((a, b) => a - b);
  return sorted[Math.ceil(0.95 * sorted.length) - 1];
}

// The SQL the two dashboards' Prisma queries amount to, for information only.
function explainStatements(requesterId: number, staffId: number): Array<[string, string]> {
  const active = `"currentStatus" NOT IN ('CLOSED','CANCELLED')`;
  return [
    ["requester: card counts (Open tickets group)", `SELECT count(*) FROM "Ticket" WHERE "requesterId" = ${requesterId} AND "currentStatus" IN ('NEW','OPEN','IN_PROGRESS','REOPENED','WAITING_FOR_REQUESTER')`],
    ["requester: Recently updated", `SELECT id, "ticketNumber", summary FROM "Ticket" WHERE "requesterId" = ${requesterId} AND "lastActivityAt" >= now() - interval '168 hours' ORDER BY "lastActivityAt" DESC, id DESC LIMIT 5`],
    ["requester: Recently resolved", `SELECT id, "ticketNumber" FROM "Ticket" WHERE "requesterId" = ${requesterId} AND "resolvedAt" >= now() - interval '168 hours' ORDER BY "resolvedAt" DESC, id DESC LIMIT 5`],
    ["staff: Unassigned count", `SELECT count(*) FROM "Ticket" WHERE ${active} AND "ownerId" IS NULL`],
    ["staff: Mine count", `SELECT count(*) FROM "Ticket" WHERE ${active} AND "ownerId" = ${staffId}`],
    ["staff: status card count (New)", `SELECT count(*) FROM "Ticket" WHERE "currentStatus" = 'NEW'`],
    ["staff: High IT Priority count", `SELECT count(*) FROM "Ticket" WHERE ${active} AND "itPriority" = 'HIGH'`],
    ["staff: My planned actions", `SELECT a.id FROM "ActionTaken" a JOIN "Ticket" t ON t.id = a."ticketId" WHERE a."assigneeId" = ${staffId} AND a.status = 'PLANNED' AND t.${active} ORDER BY a."actionAt", a.id`],
    ["staff: Recently updated", `SELECT id FROM "Ticket" WHERE ${active} AND "lastActivityAt" >= now() - interval '168 hours' ORDER BY "lastActivityAt" DESC, id DESC LIMIT 5`],
    ["staff: Urgent", `SELECT id FROM "Ticket" WHERE ${active} AND "itPriority" = 'HIGH' ORDER BY "itPriority" DESC, "createdAt" ASC, id DESC LIMIT 5`],
  ];
}

async function main() {
  const name = databaseName();
  if (name !== DATABASE) {
    console.error(`perf-smoke refuses to run: DATABASE_URL names "${name ?? "nothing"}", not ${DATABASE} (C-148).`);
    process.exit(2);
  }
  const prisma = getPrisma();
  console.log(`perf-smoke on ${DATABASE} - ${new Date().toISOString()}`);
  const { mostTickets } = await fill();

  const requesterCookie = await signIn(mostTickets.email, SEED_PASSWORDS.requester);
  const adminCookie = await signIn("panida.s@example.ac.th", SEED_PASSWORDS.administrator);
  const admin = await prisma.user.findFirstOrThrow({ where: { email: "panida.s@example.ac.th" } });

  console.log("\nEXPLAIN (ANALYZE, BUFFERS) - information only, never asserted (C-148)");
  for (const [label, sql] of explainStatements(mostTickets.id, admin.id)) {
    const plan = await prisma.$queryRawUnsafe<Array<{ "QUERY PLAN": string }>>(`EXPLAIN (ANALYZE, BUFFERS) ${sql}`);
    console.log(`\n-- ${label}\n${plan.map((r) => r["QUERY PLAN"]).join("\n")}`);
  }

  const results: Array<[string, string, number]> = [];
  results.push(["PERF-01", "GET /api/dashboard/requester as the Requester with the most Tickets", p95(await measure("/api/dashboard/requester", requesterCookie))]);
  results.push(["PERF-02", "GET /api/dashboard/staff as the Administrator", p95(await measure("/api/dashboard/staff", adminCookie))]);

  console.log(`\nWarm-up ${WARM_UP}, timed ${TIMED} per endpoint, p95 by nearest rank, limit ${LIMIT_MS} ms`);
  let failed = false;
  for (const [id, label, ms] of results) {
    const ok = ms < LIMIT_MS;
    if (!ok) failed = true;
    console.log(`${ok ? "PASS" : "FAIL"} ${id} ${label}: p95 ${ms.toFixed(1)} ms (limit ${LIMIT_MS} ms)`);
  }
  console.log(`\n${results.length - (failed ? results.filter(([, , ms]) => ms >= LIMIT_MS).length : 0)} passed, ${failed ? results.filter(([, , ms]) => ms >= LIMIT_MS).length : 0} failed`);
  await prisma.$disconnect();
  process.exit(failed ? 1 : 0);
}

main().catch(async (error) => {
  console.error(error instanceof Error ? error.message : error);
  await getPrisma().$disconnect();
  process.exit(1);
});
